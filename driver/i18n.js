// 界面语言：中文 / English。所有界面文字都在 STR 里，每条 [中文, English] 并排写，方便对照维护。
// 数据表（灯效、颜色、多媒体……）的英文名写在各自表里的 en 字段，用 L() 取。
// 纯逻辑，不碰 DOM 和 localStorage：协议层、测试也能 import。默认中文，单元测试按中文断言。

export const LANGS = ['zh', 'en'];
let lang = 'zh';
export const getLang = () => lang;
export function setLang(l) { if (LANGS.includes(l)) lang = l; }

// 数据表里的名称：{ name: 中文, en: English }
export const L = item => (lang === 'en' && item.en) || item.name;

// t('key', { n: 3 }) → 当前语言的文字，{n} 换成参数。不认识的 key 原样返回（报错信息等现成文字可以直接传进来）
export function t(key, vars) {
  const pair = STR[key];
  const s = pair ? pair[lang === 'en' ? 1 : 0] : key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : s;
}

