// 返回新的灯效块：允许修改的字段换成出厂值，其他字节保持 current 原样
export const factoryLed = current => copyLed(current, FACTORY_LED);

// 返回新的颜色表：所有灯效的 7 种颜色换回出厂调色板
export const factoryRgb = current => applyPalette(current, DEFAULT_PALETTE);

// 返回新的一层矩阵：每个按键的槽位换成出厂值，其他槽位（含签名）保持 current 原样
export function factoryMatrix(current, layer) {
  const f = FACTORY_LAYERS[layer];
  if (!f) throw new Error(t('fe.layer', { l: layer }));
  return copyMatrix(current, f);
}

// 依次恢复：灯效块 → 颜色表 → 默认层 → FN1 层（和官方一样先写灯效块再写颜色表）。每一步都是 先读 → 备份 → 写 → 读回校验。
// onBackup(part, bytes)：part 是 'led' / 'rgb' / 'layer0' / 'layer1'。UI 层负责在调用前做二次确认。
export async function factoryReset(kb, { onBackup } = {}) {
  const backup = part => onBackup ? b => onBackup(part, b) : undefined;
  const led = await kb.writeLed(factoryLed, { onBackup: backup('led') });
  const rgb = await kb.writeRgb(factoryRgb, { onBackup: backup('rgb') });
  const layer0 = await kb.writeMatrix(0, cur => factoryMatrix(cur, 0), { onBackup: backup('layer0') });
  const layer1 = await kb.writeMatrix(1, cur => factoryMatrix(cur, 1), { onBackup: backup('layer1') });
  return { led, rgb, layer0, layer1 };
}
